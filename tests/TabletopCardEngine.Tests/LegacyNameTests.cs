using FluentAssertions;
using System.Diagnostics;
using System.Text.RegularExpressions;

namespace TabletopCardEngine.Tests;

/// <summary>
/// Ensures the old name <c>OpenHoldemEngine</c>, its abbreviation <c>OHE</c>, and the old owner
/// <c>miekhra</c> do not appear in the repository tree, and that the retired engine-named API
/// (ADR-0008) is kept out. The rename to TabletopCardEngine is recorded in ADR-0007; nothing in
/// the repository stops the old names from coming back through a copied snippet, a doc written
/// from memory, or a stale branch. These tests enforce it.
/// </summary>
[TestClass]
public sealed class LegacyNameTests
{
    private static readonly Lazy<string[]> _gitLsFiles = new(ReadGitLsFiles);

    private static readonly HashSet<string> _allowlist =
    [
        // Generated by git-cliff from commit subjects that keep the old name
        "CHANGELOG.md",
        // Records the rename
        "docs/adr/0007-rename-to-tabletopcardengine.md",
        // Documents the convention that forbids the old names
        "AGENTS.md",
        // Holds the patterns and the test itself
        "tests/TabletopCardEngine.Tests/LegacyNameTests.cs",
        // SSH signing keys contain the GitHub username; the old owner's keys must remain valid
        ".github/allowed_signers",
    ];

    [TestMethod]
    public void Repository_ContainsNoLegacyName()
    {
        var errors = new List<string>();
        var oldNamePattern = new Regex("openholdem", RegexOptions.IgnoreCase);
        var abbreviationPattern = new Regex(@"OHE|Ohe[A-Z_]|\bohe\b|\bohe[_-]", RegexOptions.None);
        var ownerPattern = new Regex("miekhra", RegexOptions.IgnoreCase);

        foreach (var file in _gitLsFiles.Value)
        {
            if (_allowlist.Contains(file))
            {
                continue;
            }

            if (IsBinaryFile(file))
            {
                continue;
            }

            try
            {
                var lines = File.ReadAllLines(Path.Combine(RepositoryRoot.FullPath, file));
                for (var lineNo = 0; lineNo < lines.Length; lineNo++)
                {
                    var line = lines[lineNo];

                    if (oldNamePattern.IsMatch(line))
                    {
                        errors.Add($"{file}:{lineNo + 1}: {line.Trim()}");
                    }
                    else if (abbreviationPattern.IsMatch(line))
                    {
                        errors.Add($"{file}:{lineNo + 1}: {line.Trim()}");
                    }
                    else if (ownerPattern.IsMatch(line))
                    {
                        errors.Add($"{file}:{lineNo + 1}: {line.Trim()}");
                    }
                }
            }
            catch (UnauthorizedAccessException)
            {
                // Skip files we cannot read
            }
        }

        errors.Should().BeEmpty("the old name, its abbreviation, and the old owner must not appear in the repository");
    }

    [TestMethod]
    public void LegacyNameScan_CoversTheRepository()
    {
        _gitLsFiles.Value.Should().HaveCountGreaterThan(300,
            "the scan must cover the repository; if it returns fewer files, git ls-files may have failed");
    }

    [TestMethod]
    public void LegacyNameAllowlist_EntriesExist()
    {
        var fileSet = _gitLsFiles.Value.ToHashSet(StringComparer.Ordinal);

        foreach (var entry in _allowlist)
        {
            fileSet.Should().Contain(entry, "every allowlisted path must exist in git ls-files");
        }
    }

    [TestMethod]
    public void Repository_ContainsNoRetiredApiName()
    {
        var errors = new List<string>();
        var retiredApiPattern = new Regex(@"HoldemEngine|ApplyHoldemActionAsync|TabletopCardEngine\.(Dto|Options)\b", RegexOptions.None);
        var adrFilePattern = new Regex(@"^docs/adr/", RegexOptions.None);
        var retiredApiAllowlist = new HashSet<string>(StringComparer.Ordinal)
        {
            "CHANGELOG.md",
            "tests/TabletopCardEngine.Tests/LegacyNameTests.cs",
        };

        foreach (var file in _gitLsFiles.Value)
        {
            if (retiredApiAllowlist.Contains(file))
            {
                continue;
            }

            if (adrFilePattern.IsMatch(file))
            {
                continue;
            }

            if (IsBinaryFile(file))
            {
                continue;
            }

            try
            {
                var lines = File.ReadAllLines(Path.Combine(RepositoryRoot.FullPath, file));
                for (var lineNo = 0; lineNo < lines.Length; lineNo++)
                {
                    var line = lines[lineNo];

                    if (retiredApiPattern.IsMatch(line))
                    {
                        errors.Add($"{file}:{lineNo + 1}: {line.Trim()}");
                    }
                }
            }
            catch (UnauthorizedAccessException)
            {
                // Skip files we cannot read
            }
        }

        errors.Should().BeEmpty("the retired engine-named API must not appear in the repository; every such name is forbidden by ADR-0008");
    }

    private static string[] ReadGitLsFiles()
    {
        var psi = new ProcessStartInfo
        {
            FileName = "git",
            WorkingDirectory = RepositoryRoot.FullPath,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
        };
        psi.ArgumentList.Add("ls-files");
        psi.ArgumentList.Add("-z");

        using var process = Process.Start(psi);
        if (process is null)
        {
            throw new InvalidOperationException("Failed to start git process");
        }

        var output = process.StandardOutput.ReadToEnd();
        process.WaitForExit();

        if (process.ExitCode != 0)
        {
            var error = process.StandardError.ReadToEnd();
            throw new InvalidOperationException($"git ls-files failed with exit code {process.ExitCode}: {error}");
        }

        if (string.IsNullOrEmpty(output))
        {
            return [];
        }

        return output.Split('\0', StringSplitOptions.RemoveEmptyEntries);
    }

    private static bool IsBinaryFile(string file)
    {
        var fullPath = Path.Combine(RepositoryRoot.FullPath, file);

        try
        {
            using var stream = File.OpenRead(fullPath);
            var buffer = new byte[8000];
            var bytesRead = stream.Read(buffer, 0, buffer.Length);

            for (var i = 0; i < bytesRead; i++)
            {
                if (buffer[i] == 0)
                {
                    return true;
                }
            }

            return false;
        }
        catch (UnauthorizedAccessException)
        {
            return true;
        }
        catch (FileNotFoundException)
        {
            return true;
        }
        catch (DirectoryNotFoundException)
        {
            return true;
        }
    }
}
