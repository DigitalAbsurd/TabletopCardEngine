<#
.SYNOPSIS
    Rebuilds the vendored PHH test fixture from the upstream phh-dataset repository.

.DESCRIPTION
    Produces tests/TabletopCardEngine.Tests/Resources/phh/pluribus.phhs.gz — every hand of the
    `data/pluribus` subset packed into a single gzipped .phhs file (TOML array of tables with
    numeric headers, the layout pokerkit's HandHistory.dump_all emits, so the fixture stays
    readable by third-party PHH tooling).

    Upstream: https://github.com/uoftcprg/phh-dataset (MIT).
    Only `data/pluribus` is fetched — a full clone is ~1.7 GB, a blobless sparse clone is ~12 MB.

    This script is committed for provenance only; it is NOT part of the build or CI. Run it by
    hand when the fixture needs to be regenerated, then commit the resulting .gz and update the
    commit SHA recorded in Resources/phh/README.md.

.EXAMPLE
    pwsh ./scripts/pack-phh-fixture.ps1
#>
[CmdletBinding()]
param(
    # Existing checkout of phh-dataset. When omitted, a temporary sparse clone is made and removed.
    [string] $DatasetPath,
    [string] $OutputPath = (Join-Path $PSScriptRoot '../tests/TabletopCardEngine.Tests/Resources/phh/pluribus.phhs.gz'),
    [string] $LicenseOutputPath = (Join-Path $PSScriptRoot '../tests/TabletopCardEngine.Tests/Resources/phh/LICENSE-phh-dataset.txt')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoUrl = 'https://github.com/uoftcprg/phh-dataset.git'
$tempClone = $null

try {
    if (-not $DatasetPath) {
        $tempClone = Join-Path ([System.IO.Path]::GetTempPath()) ("phh-dataset-" + [System.Guid]::NewGuid().ToString('N'))
        Write-Host "Sparse-cloning $repoUrl into $tempClone ..."
        git clone --depth 1 --filter=blob:none --sparse $repoUrl $tempClone
        if ($LASTEXITCODE -ne 0) { throw "git clone failed with exit code $LASTEXITCODE" }
        git -C $tempClone sparse-checkout set data/pluribus
        if ($LASTEXITCODE -ne 0) { throw "git sparse-checkout failed with exit code $LASTEXITCODE" }
        $DatasetPath = $tempClone
    }

    $commitSha = (git -C $DatasetPath rev-parse HEAD).Trim()
    $pluribusRoot = Join-Path $DatasetPath 'data/pluribus'
    if (-not (Test-Path $pluribusRoot)) { throw "Not found: $pluribusRoot" }

    # Directory names are things like 30, 40b, 100b — order by (numeric prefix, suffix) so the
    # packed order is stable and human-predictable rather than lexicographic.
    $tableDirs = Get-ChildItem -Path $pluribusRoot -Directory | Sort-Object `
        @{ Expression = { [int]($_.Name -replace '\D', '') } },
        @{ Expression = { $_.Name -replace '\d', '' } }

    $outputFull = [System.IO.Path]::GetFullPath($OutputPath)
    New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetDirectoryName($outputFull)) | Out-Null

    $handCount = 0
    $fileStream = [System.IO.File]::Create($outputFull)
    try {
        $gzipStream = [System.IO.Compression.GZipStream]::new($fileStream, [System.IO.Compression.CompressionLevel]::Optimal)
        try {
            $writer = [System.IO.StreamWriter]::new($gzipStream, [System.Text.UTF8Encoding]::new($false))
            try {
                $writer.WriteLine('# Poker hand histories in PHH format, pluribus subset of the PHH dataset.')
                $writer.WriteLine("# Source: $repoUrl @ $commitSha (MIT, see LICENSE-phh-dataset.txt)")
                $writer.WriteLine("# Generated by scripts/pack-phh-fixture.ps1 — do not edit by hand.")

                foreach ($tableDir in $tableDirs) {
                    $handFiles = Get-ChildItem -Path $tableDir.FullName -Filter '*.phh' -File | Sort-Object `
                        @{ Expression = { [int][System.IO.Path]::GetFileNameWithoutExtension($_.Name) } }

                    foreach ($handFile in $handFiles) {
                        $handCount++
                        $writer.WriteLine()
                        $writer.WriteLine("# pluribus/$($tableDir.Name)/$($handFile.Name)")
                        $writer.WriteLine("[$handCount]")
                        # Upstream files have no trailing newline; TrimEnd + WriteLine normalises that.
                        $writer.WriteLine([System.IO.File]::ReadAllText($handFile.FullName).TrimEnd())
                    }
                }
            }
            finally { $writer.Dispose() }
        }
        finally { $gzipStream.Dispose() }
    }
    finally { $fileStream.Dispose() }

    Copy-Item -Path (Join-Path $DatasetPath 'LICENSE') -Destination ([System.IO.Path]::GetFullPath($LicenseOutputPath)) -Force

    $sizeKb = [math]::Round((Get-Item $outputFull).Length / 1KB, 1)
    Write-Host "Packed $handCount hands into $outputFull ($sizeKb KB)"
    Write-Host "Upstream commit: $commitSha"
}
finally {
    if ($tempClone -and (Test-Path $tempClone)) {
        # git leaves read-only objects behind on Windows; clear the attribute before deleting.
        # Cleanup must never mask the outcome of the run, hence the swallowed errors.
        try {
            Get-ChildItem -Path $tempClone -Recurse -Force -File | ForEach-Object { $_.IsReadOnly = $false }
            Remove-Item -Path $tempClone -Recurse -Force -ErrorAction Stop
        }
        catch {
            Write-Warning "Could not remove the temporary clone at ${tempClone}: $($_.Exception.Message)"
        }
    }
}
