<#
.SYNOPSIS
    Rebuilds the vendored WSOP fixed-limit PHH test fixture from the upstream phh-dataset repository.

.DESCRIPTION
    Produces tests/TabletopCardEngine.Tests/Resources/phh/wsop-fixedlimit.phhs.gz: the fixed-limit
    hands (`variant = "FT"`) of `data/wsop/2023/43/5` — the final table, day 5, of the 2023 $50,000
    Poker Players Championship — packed into a single gzipped .phhs file (TOML array of tables with
    numeric headers, the same layout the other pack-phh-*.ps1 scripts write).

    The upstream folder holds one .phh file per hand, in several variants. Only the files whose
    `variant` is FT are kept, ordered by file name and renumbered [1]..[N], with a
    `# wsop/2023/43/5/<file>` comment above each table. Whether a hand is replayable is decided at
    test time by `PhhReplayRunner.IsSupported`, so that filter has exactly one home.

    Records are copied verbatim apart from the `[N]` header.

    Upstream: https://github.com/uoftcprg/phh-dataset (MIT), read at the pinned commit below.
    Blobs are read with `git cat-file`, not checked out.

    This script is committed for provenance only; it is NOT part of the build or CI. Run it by
    hand when the fixture needs to be regenerated, then commit the resulting .gz.

.EXAMPLE
    pwsh ./scripts/pack-phh-wsop-fixedlimit-fixture.ps1
#>
[CmdletBinding()]
param(
    # Existing clone of phh-dataset. When omitted, a temporary blobless clone is made and removed.
    [string] $DatasetPath,

    # The commit every PHH fixture of this repository is read at.
    [string] $Commit = 'e47fbd5816372360bade4de5d712346fe1bb70f6',

    # Folder under data/ to pack from.
    [string] $Subset = 'wsop/2023/43/5',

    [string] $OutputPath = (Join-Path $PSScriptRoot '../tests/TabletopCardEngine.Tests/Resources/phh/wsop-fixedlimit.phhs.gz')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoUrl = 'https://github.com/uoftcprg/phh-dataset.git'
$tempClone = $null

try {
    if (-not $DatasetPath) {
        $tempClone = Join-Path ([System.IO.Path]::GetTempPath()) ("phh-dataset-" + [System.Guid]::NewGuid().ToString('N'))
        Write-Host "Cloning $repoUrl into $tempClone ..."
        # Nothing is checked out; blobs are fetched on demand below.
        git clone --filter=blob:none --no-checkout $repoUrl $tempClone
        if ($LASTEXITCODE -ne 0) { throw "git clone failed with exit code $LASTEXITCODE" }
        $DatasetPath = $tempClone
    }

    git -C $DatasetPath cat-file -e "$Commit^{commit}"
    if ($LASTEXITCODE -ne 0) { git -C $DatasetPath fetch origin $Commit }
    if ($LASTEXITCODE -ne 0) { throw "commit $Commit is not available" }

    $upstreamFiles = git -C $DatasetPath ls-tree --name-only "${Commit}:data/$Subset"
    if ($LASTEXITCODE -ne 0) { throw "git ls-tree failed for data/$Subset with exit code $LASTEXITCODE" }
    if (-not $upstreamFiles) { throw "No files under data/$Subset" }

    $outputFull = [System.IO.Path]::GetFullPath($OutputPath)
    New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetDirectoryName($outputFull)) | Out-Null

    $handCount = 0
    $fileStream = [System.IO.File]::Create($outputFull)
    try {
        $gzipStream = [System.IO.Compression.GZipStream]::new($fileStream, [System.IO.Compression.CompressionLevel]::Optimal)
        try {
            $writer = [System.IO.StreamWriter]::new($gzipStream, [System.Text.UTF8Encoding]::new($false))
            try {
                $writer.NewLine = "`n"
                $writer.WriteLine("# Poker hand histories in PHH format, the fixed-limit hands of data/$Subset of the PHH dataset.")
                $writer.WriteLine("# Source: $repoUrl @ $Commit (MIT, see LICENSE-phh-dataset.txt)")
                $writer.WriteLine("# Generated by scripts/pack-phh-wsop-fixedlimit-fixture.ps1 - do not edit by hand.")

                foreach ($upstreamFile in ($upstreamFiles | Where-Object { $_ -like '*.phh' } | Sort-Object { $_ })) {
                    $text = (git -C $DatasetPath cat-file -p "${Commit}:data/$Subset/$upstreamFile") -join "`n"
                    if ($LASTEXITCODE -ne 0) { throw "git cat-file failed for $upstreamFile with exit code $LASTEXITCODE" }

                    if ($text -notmatch '(?m)^variant = ''FT''\s*$') { continue }

                    $handCount++
                    $writer.WriteLine()
                    $writer.WriteLine("# $Subset/$upstreamFile")
                    $writer.WriteLine("[$handCount]")
                    $writer.WriteLine($text.TrimEnd())
                }
            }
            finally { $writer.Dispose() }
        }
        finally { $gzipStream.Dispose() }
    }
    finally { $fileStream.Dispose() }

    $sizeKb = [math]::Round((Get-Item $outputFull).Length / 1KB, 1)
    Write-Host "Packed $handCount fixed-limit hands into $outputFull ($sizeKb KB)"
    Write-Host "Upstream commit: $Commit"
}
finally {
    if ($tempClone -and (Test-Path $tempClone)) {
        # git leaves read-only objects behind on Windows; clear the attribute before deleting.
        # Cleanup must never mask the outcome of the run, hence the swallowed errors.
        try {
            Get-ChildItem -Path $tempClone -Recurse -Force -File | ForEach-Object { $_.IsReadOnly = $false }
            Remove-Item -Path $tempClone -Recurse -Force -ErrorAction Stop
        }
        catch {
            Write-Warning "Could not remove the temporary clone at ${tempClone}: $($_.Exception.Message)"
        }
    }
}
