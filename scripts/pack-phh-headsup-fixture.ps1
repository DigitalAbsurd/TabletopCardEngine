<#
.SYNOPSIS
    Rebuilds the vendored heads-up PHH test fixture from the upstream phh-dataset repository.

.DESCRIPTION
    Produces tests/OpenHoldemEngine.Tests/Resources/phh/handhq-headsup.phhs.gz — the heads-up hands
    of the first few `data/handhq` files, packed into a single gzipped .phhs file (TOML array of
    tables with numeric headers, the same layout pack-phh-fixture.ps1 writes).

    Why a second script rather than a switch on the first: the two subsets have different shapes on
    disk. `data/pluribus` is one .phh file per hand; `data/handhq` is .phhs files holding a thousand
    hands each, so packing means splitting records out and renumbering them.

    Only heads-up hands are kept, which is the point of the fixture — the surrounding 6- to 9-handed
    hands are the shape `pluribus.phhs.gz` already covers exhaustively. Heads-up is decided on the
    one mechanical criterion the file states outright: `blinds_or_straddles` has exactly two entries.
    Everything else a hand has to satisfy to be replayable is decided at test time by
    `PhhReplayRunner.IsSupported`, so that filter has exactly one home.

    Records are copied verbatim apart from the `[N]` header, so the fixture stays a faithful
    vendored copy and stays readable by third-party PHH tooling.

    Upstream: https://github.com/uoftcprg/phh-dataset (MIT).
    Blobs are read with `git cat-file` rather than checked out — a full checkout of the handhq
    subset is several gigabytes, and this needs a handful of files from it.

    This script is committed for provenance only; it is NOT part of the build or CI. Run it by
    hand when the fixture needs to be regenerated, then commit the resulting .gz and update the
    commit SHA recorded in Resources/phh/README.md.

.EXAMPLE
    pwsh ./scripts/pack-phh-headsup-fixture.ps1
#>
[CmdletBinding()]
param(
    # Existing clone of phh-dataset. When omitted, a temporary blobless clone is made and removed.
    [string] $DatasetPath,

    # Folder under data/ to pack from. Its files are taken in numeric order.
    [string] $Subset = 'handhq/PS-2009-07-01_2009-07-23_50NLH_OBFU/0.5',

    # How many upstream files to read. Five gives roughly 2 350 heads-up hands.
    [int] $FileCount = 5,

    [string] $OutputPath = (Join-Path $PSScriptRoot '../tests/OpenHoldemEngine.Tests/Resources/phh/handhq-headsup.phhs.gz')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoUrl = 'https://github.com/uoftcprg/phh-dataset.git'
$tempClone = $null

# `[3]` and everything up to the next header or end of text. Records are separated by a blank line.
$recordPattern = '(?ms)^\[(?<index>\d+)\][ \t]*\r?\n(?<body>.*?)(?=^\[\d+\][ \t]*\r?\n|\z)'

try {
    if (-not $DatasetPath) {
        $tempClone = Join-Path ([System.IO.Path]::GetTempPath()) ("phh-dataset-" + [System.Guid]::NewGuid().ToString('N'))
        Write-Host "Cloning $repoUrl into $tempClone ..."
        # No sparse paths are set: nothing is checked out, and blobs are fetched on demand below.
        git clone --depth 1 --filter=blob:none --sparse $repoUrl $tempClone
        if ($LASTEXITCODE -ne 0) { throw "git clone failed with exit code $LASTEXITCODE" }
        $DatasetPath = $tempClone
    }

    $commitSha = (git -C $DatasetPath rev-parse HEAD).Trim()

    $upstreamFiles = git -C $DatasetPath ls-tree --name-only "HEAD:data/$Subset"
    if ($LASTEXITCODE -ne 0) { throw "git ls-tree failed for data/$Subset with exit code $LASTEXITCODE" }
    if (-not $upstreamFiles) { throw "No files under data/$Subset" }

    # Upstream names files `... handhq_137-OBFUSCATED.phhs`; order by that number, not lexically.
    $selectedFiles = $upstreamFiles |
        Sort-Object @{ Expression = { [int]($_ -replace '\D', '') } } |
        Select-Object -First $FileCount

    $outputFull = [System.IO.Path]::GetFullPath($OutputPath)
    New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetDirectoryName($outputFull)) | Out-Null

    $handCount = 0
    $readCount = 0
    $fileStream = [System.IO.File]::Create($outputFull)
    try {
        $gzipStream = [System.IO.Compression.GZipStream]::new($fileStream, [System.IO.Compression.CompressionLevel]::Optimal)
        try {
            $writer = [System.IO.StreamWriter]::new($gzipStream, [System.Text.UTF8Encoding]::new($false))
            try {
                $writer.WriteLine("# Poker hand histories in PHH format, heads-up hands of the handhq subset of the PHH dataset.")
                $writer.WriteLine("# Subset: data/$Subset, first $FileCount files.")
                $writer.WriteLine("# Source: $repoUrl @ $commitSha (MIT, see LICENSE-phh-dataset.txt)")
                $writer.WriteLine("# Generated by scripts/pack-phh-headsup-fixture.ps1 — do not edit by hand.")

                foreach ($upstreamFile in $selectedFiles) {
                    $text = (git -C $DatasetPath cat-file -p "HEAD:data/$Subset/$upstreamFile") -join "`n"
                    if ($LASTEXITCODE -ne 0) { throw "git cat-file failed for $upstreamFile with exit code $LASTEXITCODE" }

                    # The source comment has to be one whitespace-free token, because that is what
                    # PhhReader recovers it with; upstream file names contain spaces.
                    $sourceFile = "$Subset/$($upstreamFile -replace '\s', '_')"

                    foreach ($match in [regex]::Matches($text, $recordPattern)) {
                        $readCount++
                        $body = $match.Groups['body'].Value.TrimEnd()

                        # Two entries in blinds_or_straddles means two players, which is the whole
                        # point of this fixture. Every other requirement is IsSupported's business.
                        if ($body -notmatch '(?m)^blinds_or_straddles = \[[^,\]]+,[^,\]]+\]\s*$') { continue }

                        $handCount++
                        $writer.WriteLine()
                        $writer.WriteLine("# $sourceFile#$($match.Groups['index'].Value)")
                        $writer.WriteLine("[$handCount]")
                        $writer.WriteLine($body)
                    }
                }
            }
            finally { $writer.Dispose() }
        }
        finally { $gzipStream.Dispose() }
    }
    finally { $fileStream.Dispose() }

    $sizeKb = [math]::Round((Get-Item $outputFull).Length / 1KB, 1)
    Write-Host "Kept $handCount heads-up hands out of $readCount read, into $outputFull ($sizeKb KB)"
    Write-Host "Upstream commit: $commitSha"
}
finally {
    if ($tempClone -and (Test-Path $tempClone)) {
        # git leaves read-only objects behind on Windows; clear the attribute before deleting.
        # Cleanup must never mask the outcome of the run, hence the swallowed errors.
        try {
            Get-ChildItem -Path $tempClone -Recurse -Force -File | ForEach-Object { $_.IsReadOnly = $false }
            Remove-Item -Path $tempClone -Recurse -Force -ErrorAction Stop
        }
        catch {
            Write-Warning "Could not remove the temporary clone at ${tempClone}: $($_.Exception.Message)"
        }
    }
}
