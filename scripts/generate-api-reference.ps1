<#
.SYNOPSIS
    Generates the Markdown API reference of the seven packages into docs/api/ with DefaultDocumentation.

.DESCRIPTION
    Runs the DefaultDocumentation.Console local tool (ADR-0009) over the built assembly of every
    package in TabletopCardEngine.Packages.slnf, into a temporary directory, one sub-directory per
    package. The generator deletes every .md file in its output directory, so it never writes into
    docs/api/ itself. Each page is then normalised: outside fenced code blocks `\<` becomes `&lt;`
    and `\>` becomes `&gt;` (Python-Markdown cannot escape `<`), and the file is written as UTF-8
    without BOM, LF line endings and exactly one final newline.

    The `nav` block for mkdocs.yml is built from the generated pages, because MkDocs fails its strict
    build on a page the `nav` omits.

    Without -Update the generated pages and the nav block are compared with docs/api/<Package>/ and
    the block between the GENERATED markers in mkdocs.yml: every missing, extra or different path is
    printed and the exit code is 1. With -Update the package directories and the block are replaced.
    Everything else under docs/api/ is left alone.

.EXAMPLE
    pwsh ./scripts/generate-api-reference.ps1 -Update
#>
[CmdletBinding()]
param(
    [ValidateSet('Debug', 'Release')]
    [string] $Configuration = 'Release',
    [switch] $NoBuild,
    [switch] $Update
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
$beginMarker = '# BEGIN GENERATED by scripts/generate-api-reference.ps1'
$endMarker = '# END GENERATED'

function Invoke-Native {
    param([string] $Command, [string[]] $Arguments)
    & $Command @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$Command $($Arguments -join ' ') failed with exit code $LASTEXITCODE."
    }
}

# Content as the repository stores it: LF, one final newline, and the generator's `\<` made safe.
function ConvertTo-PageText {
    param([string] $Text)
    $inFence = $false
    $lines = foreach ($line in ($Text -split "\r?\n")) {
        if ($line.StartsWith('```')) {
            $inFence = -not $inFence
            $line
        }
        elseif ($inFence) {
            $line
        }
        else {
            $line.Replace('\<', '&lt;').Replace('\>', '&gt;')
        }
    }
    return (($lines -join "`n").TrimEnd("`n") + "`n")
}

# `HoldemResult_T_` is how the generator spells `HoldemResult<T>`.
function Get-TypeTitle {
    param([string] $Name)
    if ($Name -match '^(.*?)_(.+)_$') {
        return "$($Matches[1])<$($Matches[2])>"
    }
    return $Name
}

$filter = Get-Content -Raw (Join-Path $repoRoot 'TabletopCardEngine.Packages.slnf') | ConvertFrom-Json
# The .slnf stores Windows separators, and `\` is no separator on Linux.
$packages = @($filter.solution.projects | ForEach-Object { [IO.Path]::GetFileNameWithoutExtension(($_ -replace '\\', '/')) })
$core = 'TabletopCardEngine'
$packages = @($core) + @($packages | Where-Object { $_ -ne $core })

Push-Location $repoRoot
try {
    Invoke-Native dotnet @('tool', 'restore')
    if (-not $NoBuild) {
        Invoke-Native dotnet @('build', 'TabletopCardEngine.Packages.slnf', '-c', $Configuration)
    }
    foreach ($package in $packages) {
        $dll = Join-Path $repoRoot "src/$package/bin/$Configuration/net10.0/$package.dll"
        if (-not (Test-Path $dll)) {
            throw "$dll not found. Run without -NoBuild, or build $Configuration first."
        }
    }

    $tmp = Join-Path ([IO.Path]::GetTempPath()) ('tce-api-' + [Guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $tmp | Out-Null
    try {
        $config = Join-Path $repoRoot 'eng/api-reference/DefaultDocumentation.json'
        $coreLinks = Join-Path $tmp 'core.links'
        $externLinks = "$coreLinks|" + (Join-Path $repoRoot 'eng/api-reference/opentelemetry.links')

        $pages = @{}
        $nav = New-Object System.Collections.Generic.List[string]
        foreach ($package in $packages) {
            # Relative paths given with -j resolve against the configuration file, so pass absolute ones.
            $out = Join-Path $tmp $package
            $arguments = @(
                'tool', 'run', 'defaultdocumentation',
                '-j', $config,
                '-a', (Join-Path $repoRoot "src/$package/bin/$Configuration/net10.0/$package.dll"),
                '-o', $out,
                '-n', 'index')
            if ($package -eq $core) {
                $arguments += @('-l', $coreLinks, '-b', '../TabletopCardEngine/')
            }
            else {
                $arguments += @('-e', $externLinks)
            }
            Invoke-Native dotnet $arguments | Out-Null

            $texts = @{}
            foreach ($file in Get-ChildItem $out -Filter *.md) {
                $texts[$file.Name] = ConvertTo-PageText ([IO.File]::ReadAllText($file.FullName))
            }
            $pages[$package] = $texts

            $names = @($texts.Keys | Where-Object { $_ -ne 'index.md' } | ForEach-Object { $_.Substring(0, $_.Length - 3) })
            $namespaces = @($names | Where-Object { $texts["$_.md"] -match '(?m)^## .+ Namespace\s*$' } | Sort-Object { $_ } -CaseSensitive)
            $nav.Add("          - ${package}:")
            $nav.Add("              - 'Assembly': api/$package/index.md")
            foreach ($namespace in $namespaces) {
                $nav.Add("              - '${namespace}':")
                $nav.Add("                  - 'Namespace': api/$package/$namespace.md")
                $mine = foreach ($name in ($names | Where-Object { $namespaces -notcontains $_ })) {
                    $longest = $namespaces | Where-Object { $name.StartsWith("$_.") } | Sort-Object Length -Descending | Select-Object -First 1
                    if ($longest -eq $namespace) {
                        [pscustomobject]@{ File = $name; Title = Get-TypeTitle $name.Substring($namespace.Length + 1) }
                    }
                }
                foreach ($type in @($mine | Sort-Object { $_.Title } -CaseSensitive)) {
                    $nav.Add("                  - '$($type.Title)': api/$package/$($type.File).md")
                }
            }
        }
        $navText = ($nav -join "`n")

        $mkdocsPath = Join-Path $repoRoot 'mkdocs.yml'
        $mkdocs = [IO.File]::ReadAllText($mkdocsPath)
        $blockPattern = '(?s)(?<=' + [regex]::Escape($beginMarker) + '\r?\n).*?(?=[ \t]*' + [regex]::Escape($endMarker) + ')'
        $blockMatch = [regex]::Match($mkdocs, $blockPattern)
        if (-not $blockMatch.Success) {
            throw "mkdocs.yml has no '$beginMarker' ... '$endMarker' block."
        }
        $currentNav = ($blockMatch.Value -replace "\r?\n$", '')

        if ($Update) {
            foreach ($package in $packages) {
                $target = Join-Path $repoRoot "docs/api/$package"
                if (Test-Path $target) {
                    Remove-Item $target -Recurse -Force
                }
                New-Item -ItemType Directory -Path $target | Out-Null
                foreach ($name in $pages[$package].Keys) {
                    [IO.File]::WriteAllText((Join-Path $target $name), $pages[$package][$name], $utf8NoBom)
                }
            }
            $replacement = $navText + "`n"
            $mkdocs = [regex]::Replace($mkdocs, $blockPattern, [System.Text.RegularExpressions.MatchEvaluator] { param($m) $replacement })
            [IO.File]::WriteAllText($mkdocsPath, $mkdocs, $utf8NoBom)
            Write-Host "docs/api updated: $(($pages.Values | ForEach-Object { $_.Count } | Measure-Object -Sum).Sum) pages."
            return
        }

        $differences = New-Object System.Collections.Generic.List[string]
        foreach ($package in $packages) {
            $target = Join-Path $repoRoot "docs/api/$package"
            $existing = @{}
            if (Test-Path $target) {
                foreach ($file in Get-ChildItem $target -Filter *.md) {
                    $existing[$file.Name] = [IO.File]::ReadAllText($file.FullName)
                }
            }
            foreach ($name in $pages[$package].Keys) {
                if (-not $existing.ContainsKey($name)) {
                    $differences.Add("missing: docs/api/$package/$name")
                }
                elseif ($existing[$name] -cne $pages[$package][$name]) {
                    $differences.Add("different: docs/api/$package/$name")
                }
            }
            foreach ($name in $existing.Keys) {
                if (-not $pages[$package].ContainsKey($name)) {
                    $differences.Add("extra: docs/api/$package/$name")
                }
            }
        }
        if ($currentNav -cne $navText) {
            $differences.Add('mkdocs.yml (nav)')
        }
        if ($differences.Count -gt 0) {
            $differences | Sort-Object | ForEach-Object { Write-Host $_ }
            Write-Host 'docs/api is out of date. Run: pwsh ./scripts/generate-api-reference.ps1 -Update'
            exit 1
        }
        Write-Host 'docs/api is up to date.'
    }
    finally {
        Remove-Item $tmp -Recurse -Force -ErrorAction SilentlyContinue
    }
}
finally {
    Pop-Location
}
