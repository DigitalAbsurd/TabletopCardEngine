<#
.SYNOPSIS
    Rebuilds the vendored full-ring PHH test fixture from the upstream phh-dataset repository.

.DESCRIPTION
    Produces tests/TabletopCardEngine.Tests/Resources/phh/handhq-fullring.phhs.gz — the full-ring (7 to 10 seated)
    hands from two subsets of the handhq data, packed into a single gzipped .phhs file (TOML array of tables with
    numeric headers, the same layout pack-phh-headsup-fixture.ps1 writes).

    Full-ring hands are kept by one mechanical criterion the file states outright: `blinds_or_straddles` has 7 to 9
    entries (for full-ring 7-9 players) or exactly 10 entries (for 10-handed). Everything else a hand has to satisfy
    to be replayable is decided at test time by `PhhReplayRunner.IsSupported`, so that filter has exactly one home.

    Records are copied verbatim apart from the `[N]` header, so the fixture stays a faithful vendored copy and stays
    readable by third-party PHH tooling.

    Upstream: https://github.com/uoftcprg/phh-dataset (MIT).
    Blobs are read with `git cat-file` rather than checked out — a full checkout of the handhq subset is several
    gigabytes, and this needs a handful of files from it.

    This script is committed for provenance only; it is NOT part of the build or CI. Run it by hand when the fixture
    needs to be regenerated, then commit the resulting .gz and update the commit SHA recorded in
    Resources/phh/README.md.

.EXAMPLE
    pwsh ./scripts/pack-phh-fullring-fixture.ps1
#>
[CmdletBinding()]
param(
    # Existing clone of phh-dataset. When omitted, a temporary blobless clone is made and removed.
    [string] $DatasetPath,

    # First subset: 7-9 handed hands from PokerStars 50NLH. How many upstream files to read.
    [int] $FirstFileCount = 5,

    # Second subset: 10-handed hands from PartyPoker 400NLH. How many upstream files to read.
    [int] $SecondFileCount = 20,

    [string] $OutputPath = (Join-Path $PSScriptRoot '../tests/TabletopCardEngine.Tests/Resources/phh/handhq-fullring.phhs.gz')
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$repoUrl = 'https://github.com/uoftcprg/phh-dataset.git'
$tempClone = $null

# `[3]` and everything up to the next header or end of text. Records are separated by a blank line.
$recordPattern = '(?ms)^\[(?<index>\d+)\][ \t]*\r?\n(?<body>.*?)(?=^\[\d+\][ \t]*\r?\n|\z)'

try {
    if (-not $DatasetPath) {
        $tempClone = Join-Path ([System.IO.Path]::GetTempPath()) ("phh-dataset-" + [System.Guid]::NewGuid().ToString('N'))
        Write-Host "Cloning $repoUrl into $tempClone ..."
        # No sparse paths are set: nothing is checked out, and blobs are fetched on demand below.
        git clone --depth 1 --filter=blob:none --sparse $repoUrl $tempClone
        if ($LASTEXITCODE -ne 0) { throw "git clone failed with exit code $LASTEXITCODE" }
        $DatasetPath = $tempClone
    }

    $commitSha = (git -C $DatasetPath rev-parse HEAD).Trim()

    $outputFull = [System.IO.Path]::GetFullPath($OutputPath)
    New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetDirectoryName($outputFull)) | Out-Null

    $handCount = 0
    $readCount = 0
    $histogram = @{}

    $fileStream = [System.IO.File]::Create($outputFull)
    try {
        $gzipStream = [System.IO.Compression.GZipStream]::new($fileStream, [System.IO.Compression.CompressionLevel]::Optimal)
        try {
            $writer = [System.IO.StreamWriter]::new($gzipStream, [System.Text.UTF8Encoding]::new($false))
            try {
                $writer.WriteLine("# Poker hand histories in PHH format, full-ring hands of the handhq subset of the PHH dataset.")
                $writer.WriteLine("# Sources:")
                $writer.WriteLine("#   - data/handhq/PS-2009-07-01_2009-07-23_50NLH_OBFU/0.5, first $FirstFileCount files, hands with 7-9 players")
                $writer.WriteLine("#   - data/handhq/PTY-2009-07-01_2009-07-23_400NLH_OBFU/4, first $SecondFileCount files, hands with exactly 10 players")
                $writer.WriteLine("# Source: $repoUrl @ $commitSha (MIT, see LICENSE-phh-dataset.txt)")
                $writer.WriteLine("# Generated by scripts/pack-phh-fullring-fixture.ps1 — do not edit by hand.")

                # First source: 7-9 handed
                $subset1 = 'handhq/PS-2009-07-01_2009-07-23_50NLH_OBFU/0.5'
                $upstreamFiles = git -C $DatasetPath ls-tree --name-only "HEAD:data/$subset1"
                if ($LASTEXITCODE -ne 0) { throw "git ls-tree failed for data/$subset1 with exit code $LASTEXITCODE" }
                if (-not $upstreamFiles) { throw "No files under data/$subset1" }

                $selectedFiles = $upstreamFiles |
                    Sort-Object @{ Expression = { [int]($_ -replace '\D', '') } } |
                    Select-Object -First $FirstFileCount

                foreach ($upstreamFile in $selectedFiles) {
                    $text = (git -C $DatasetPath cat-file -p "HEAD:data/$subset1/$upstreamFile") -join "`n"
                    if ($LASTEXITCODE -ne 0) { throw "git cat-file failed for $upstreamFile with exit code $LASTEXITCODE" }

                    $sourceFile = "$subset1/$($upstreamFile -replace '\s', '_')"

                    foreach ($match in [regex]::Matches($text, $recordPattern)) {
                        $readCount++
                        $body = $match.Groups['body'].Value.TrimEnd()

                        # 7 to 9 entries in blinds_or_straddles means 7-9 players (full-ring).
                        if ($body -notmatch '(?m)^blinds_or_straddles = \[([^,\]]+,){6,8}[^,\]]+\]\s*$') { continue }

                        # Count players by counting commas + 1
                        if ($body -match '(?m)^blinds_or_straddles = \[((?:[^,\]]+,)*[^,\]]+)\]\s*$') {
                            $playerCount = ($matches[1] -split ',').Count
                            $histogram[$playerCount] = ($histogram[$playerCount] ?? 0) + 1
                        }

                        $handCount++
                        $writer.WriteLine()
                        $writer.WriteLine("# $sourceFile#$($match.Groups['index'].Value)")
                        $writer.WriteLine("[$handCount]")
                        $writer.WriteLine($body)
                    }
                }

                # Second source: 10-handed
                $subset2 = 'handhq/PTY-2009-07-01_2009-07-23_400NLH_OBFU/4'
                $upstreamFiles = git -C $DatasetPath ls-tree --name-only "HEAD:data/$subset2"
                if ($LASTEXITCODE -ne 0) { throw "git ls-tree failed for data/$subset2 with exit code $LASTEXITCODE" }
                if (-not $upstreamFiles) { throw "No files under data/$subset2" }

                $selectedFiles = $upstreamFiles |
                    Sort-Object @{ Expression = { [int]($_ -replace '\D', '') } } |
                    Select-Object -First $SecondFileCount

                foreach ($upstreamFile in $selectedFiles) {
                    $text = (git -C $DatasetPath cat-file -p "HEAD:data/$subset2/$upstreamFile") -join "`n"
                    if ($LASTEXITCODE -ne 0) { throw "git cat-file failed for $upstreamFile with exit code $LASTEXITCODE" }

                    $sourceFile = "$subset2/$($upstreamFile -replace '\s', '_')"

                    foreach ($match in [regex]::Matches($text, $recordPattern)) {
                        $readCount++
                        $body = $match.Groups['body'].Value.TrimEnd()

                        # Exactly 10 entries in blinds_or_straddles means 10 players.
                        if ($body -notmatch '(?m)^blinds_or_straddles = \[([^,\]]+,){9}[^,\]]+\]\s*$') { continue }

                        $histogram[10] = ($histogram[10] ?? 0) + 1

                        $handCount++
                        $writer.WriteLine()
                        $writer.WriteLine("# $sourceFile#$($match.Groups['index'].Value)")
                        $writer.WriteLine("[$handCount]")
                        $writer.WriteLine($body)
                    }
                }
            }
            finally { $writer.Dispose() }
        }
        finally { $gzipStream.Dispose() }
    }
    finally { $fileStream.Dispose() }

    $sizeKb = [math]::Round((Get-Item $outputFull).Length / 1KB, 1)
    Write-Host "Histogram:"
    foreach ($players in ($histogram.Keys | Sort-Object)) {
        Write-Host "  $players players: $($histogram[$players]) hands"
    }
    Write-Host "Total: $handCount full-ring hands out of $readCount read, into $outputFull ($sizeKb KB)"
    Write-Host "Upstream commit: $commitSha"
}
finally {
    if ($tempClone -and (Test-Path $tempClone)) {
        # git leaves read-only objects behind on Windows; clear the attribute before deleting.
        # Cleanup must never mask the outcome of the run, hence the swallowed errors.
        try {
            Get-ChildItem -Path $tempClone -Recurse -Force -File | ForEach-Object { $_.IsReadOnly = $false }
            Remove-Item -Path $tempClone -Recurse -Force -ErrorAction Stop
        }
        catch {
            Write-Warning "Could not remove the temporary clone at ${tempClone}: $($_.Exception.Message)"
        }
    }
}
